#!/usr/bin/env node
// gen-router.js — generate the Figma side of the Jev router from build/router-table.json.
//   node build/gen-router.js          → writes build/templates/route.use_figma.js and the
//                                        JEV-ROUTER section of sap-figma-agent/SKILL.md
//   node build/gen-router.js --check  → exit 1 if either is out of date (used by the test)
// Edit the table (or route-core.js / route-apply.figma.js), never the generated text.
const fs = require('fs');
const path = require('path');
const B = __dirname, ROOT = path.dirname(B);
const T = require('./router-table.json');
const SKILL = path.join(ROOT, '.claude/skills/sap-figma-agent/SKILL.md');
const BLOCK_OUT = path.join(B, 'templates/route.use_figma.js');
const BEGIN = '<!-- JEV-ROUTER:BEGIN — generated by build/gen-router.js from build/router-table.json. Do not edit here: edit the table, run `node build/gen-router.js`. -->';
const END = '<!-- JEV-ROUTER:END -->';

// the table subset the Figma block needs (no keys the block never reads)
const sub = {
  gate1_mode: T.gate1_mode,
  gate3_component: { rules: T.gate3_component.rules.map(r => ({ words: r.words, component: r.component })) },
  gate4_state: T.gate4_state,
  act_route: T.act_route,
};
const strip = o => JSON.parse(JSON.stringify(o, (k, v) => (k === '_doc' || k === 'verified' ? undefined : v)));
// the block is pasted into the skill (65,536-char limit in Figma) → no comments, no indent
const mini = f => fs.readFileSync(path.join(B, f), 'utf8').split('\n').map(l => l.trim())
  .filter(l => l && !l.startsWith('//') && !l.startsWith('if (typeof module')).join('\n');
const B2 = x => JSON.stringify([T.act_route[x].key, T.act_route[x].weight]);
const STATES = JSON.stringify(Object.fromEntries(Object.entries(T.gate4_state.keys).map(([k, v]) => [k, { props: v.props, values: v.values }])));
const apply = mini('templates/route-apply.figma.js')
  .replace('__SEL__', B2('frame_active_border')).replace('__NORMAL__', B2('frame_normal_border')).replace('__STATES__', STATES);
// saved ONCE per file in sharedPluginData; the key carries a hash, so a new skill version re-installs itself
const KEY = 'act_' + require('crypto').createHash('sha1').update(apply).digest('hex').slice(0, 6);
const INSTALL = `figma.root.setSharedPluginData('sapfiori', '${KEY}', ${JSON.stringify(apply)});\nreturn 'installed ${KEY}';`;
const CALL = `const A = { node: '176:4283', state: 'on', border: 'selected', exclusive: true };
const c = figma.root.getSharedPluginData('sapfiori', '${KEY}');
return c ? await new (Object.getPrototypeOf(async () => {}).constructor)('A', c)(A) : 'INSTALL FIRST';`;
const block = apply;   // build/templates/route.use_figma.js = the saved code (tests run it; A is its parameter)

// ── BUILD KIT: helpers (sap-kit.prelude.js) + SAP keys, saved once per file for the Figma Agent ──
const KITJ = require('../knowledge/live/kit.json');
const FK = { c: {}, v: {}, t: {}, i: {} };
for (const n of T.figma_kit.components) { if (!KITJ.components[n]) throw new Error(`figma_kit: ${n} not in kit.json`); FK.c[n] = KITJ.components[n].key; }
for (const [n, v] of Object.entries(KITJ.vars)) if (v.split('|')[1] === 'C') FK.v[n.split('/').pop()] = v.split('|')[0];
FK.v[T.act_route.frame_active_border.token] = T.act_route.frame_active_border.key;   // verified live, not in kit.json
for (const [n, v] of Object.entries(KITJ.text)) FK.t[n] = v.split('|')[0];
for (const [n, v] of Object.entries(KITJ.icons)) FK.i[n.split('/').pop()] = v;
for (const [n, v] of Object.entries(require('../knowledge/live/icons-extra.json').icons)) FK.i[n] = v.key;   // suitcase, meal, share-arrow…
const prelude = mini('templates/sap-kit.prelude.js') + '\nreturn { I, T, fill, stroke, space, AL, put, sub, setP, WARN, KIT };';
const BKEY = 'build_' + require('crypto').createHash('sha1').update(JSON.stringify(FK) + prelude).digest('hex').slice(0, 6);
const BUILD_LOAD = `const _k = figma.root.getSharedPluginData('sapfiori', '${BKEY}');
if (!_k) return 'INSTALL BUILD FIRST';
const { I, T, fill, stroke, space, AL, put, sub, setP, WARN, KIT } = await new (Object.getPrototypeOf(async () => {}).constructor)(_k)();`;
const BUILD_INSTALL = `const KIT = ${JSON.stringify(FK)};
const P = ${JSON.stringify(prelude)};
figma.root.setSharedPluginData('sapfiori', '${BKEY}', 'const KIT = ' + JSON.stringify(KIT) + ';\\n' + P);
return 'installed ${BKEY}';`;

const md = s => s.map(w => '`' + w + '`').join(', ');
const g1 = T.gate1_mode, g4 = T.gate4_state;
const section = `${BEGIN}

## 🚦 STEP −1 — JEV ROUTER: look up, do not reason (every request, first)

The router gives each request a **type** and sends it to **one** handler. Tables, not
thinking. **The first line you write is the trace** — \`▸ routed: <mode> · <floorplan> ·
<component> · <prop>=<value>\` — then you run the one handler. No trace = not routed.
An unclear word → show the candidates and ask. **Never guess.**

**GATE 1 — MODE** (per clause; split on \`,\` \`;\` \`then\`; full word lists: \`build/router-table.json\`)
1. new/create word **and** a screen noun (dialog, page, form, wizard…) → **THINK**
2. a THINK word (build, suggest, better, improve, what is wrong, based on this…) → **THINK**
3. a property word or a number with padding/gap — property words **beat** "add" → **⚡ ACT**
4. a structure word (add, remove, move, swap, column, row, icon…) → **🔧 QUICK**
5. no signal → **THINK**. ACT part + THINK part → **SPLIT**: ACT part now, then plan.

| Mode | Handler |
|---|---|
| ⚡ ACT | ONE short \`use_figma\` call: the ACT block below with \`A\` filled. No plan, no screenshot. Reply = the trace line. |
| 🔧 QUICK | runtime build (Step 2) for the named nodes only; Step 3 check; one screenshot. |
| 🧠 THINK | Step 0 → 5. Gate 2 + 3 pre-fill the Step 1 inventory; you add ASCII + confidence, then wait. A reference image + an existing node → **MATCH MODE**. |

**GATE 2 — FLOORPLAN** (THINK only; first match wins; no match → from the image, else ask)

| Floorplan | Task words |
|---|---|
${T.gate2_floorplan.rules.map(r => `| ${r.floorplan} | ${md(r.words)} |`).join('\n')}

**GATE 3 — COMPONENT** (longest phrase wins)

| Component | Words | Key |
|---|---|---|
${T.gate3_component.rules.map(r => `| ${r.component} | ${r.words.join(', ')} | \`${r.key}\` |`).join('\n')}

Ask, never guess: ${T.gate3_component.candidates.map(c => `"${c.word}" → ${c.options.join(' / ')}`).join(' · ')}.

**GATE 4 — STATE** (the kit names one state in different ways — take the FIRST prop the
component really has, then the FIRST value that prop really offers; never a fixed value)

| \`A.state\` | Words | Props → values it tries, in order (the saved code reads the node's real options) |
|---|---|---|
${Object.entries(g4.keys).map(([k, s]) => `| \`'${k}'\` | ${s.words.join(', ')} | ${s.props.join('/')} → ${s.values.join('/')} |`).join('\n')}

On a plain frame / card (no component): on / active → border \`${T.act_route.frame_active_border.token}\` ${T.act_route.frame_active_border.weight}px · off → border \`${T.act_route.frame_normal_border.token}\` ${T.act_route.frame_normal_border.weight}px.
Numbers snap to the SAP scale ${T.act_route.sap_scale.join('/')}: ${Object.entries(T.act_route.number_targets).map(([w, o]) => `"${w} N" → ${o}`).join(' · ')}.

**GATE 0 — IMAGE** (labels come from \`measure-ref.py --json\`; in Figma, label by eye. The audit uses the same table)

| measure-ref label (prefix) | Size rule → component |
|---|---|
${T.image_labels.rules.map(r => `| ${r.label} | ${r.size.map(s => ('w_max' in s ? `w≤${s.w_max} ` : 'h_max' in s ? `h≤${s.h_max} ` : 'else ') + '→ ' + (s.component || s.else) + (s.options ? ' (' + s.options.join('/') + ')' : '') + (s.density ? ' ' + s.density : '') + (s.state ? ' state ' + s.state : '')).join(' · ')} |`).join('\n')}

**Read like a person (THINK / MATCH with an image):** Z pattern — top-left → right, then down.
Split into sections A, B, C… (side-by-side = one band, left → right). For each, FIRST describe
it in plain words with positions ("B: three cards; each: radio left, title next to it, price
under it, divider, icon + text"), THEN map each thing to SAP: component · state · text style ·
colour token. Then list every element. Small parts belong to the section they sit in.

**Colour by ROLE, never by photo:** ${Object.entries(T.colour_roles).filter(([k]) => k !== '_doc').map(([k, v]) => `${k.replace(/_/g, ' ')} \`${v[0]}\``).join(' · ')}. CTA = Button \`Type=Primary\` — never paint a brand colour; a reference colour with no SAP role keeps the component default.

**One SAP icon per meaning:** ${Object.entries(Object.entries(T.icon_meanings).filter(([k]) => k !== '_doc').reduce((g, [m, i]) => ((g[i === null ? 'ASK' : i] ||= []).push(m.replace(/_/g, ' ')), g), {})).map(([i, ms]) => i === 'ASK' ? `${ms.join('/')} → **ask**` : `\`${i}\` ${ms.join('/')}`).join(' · ')}. Never the same icon for different meanings. Logos: crop from the reference, never a colour block.

Container = plain auto-layout FRAME, no fill; border \`${T.image_labels.container.border_token}\`, selected \`${T.image_labels.container.selected_border_token}\`. A label not here → list it as **unmapped** in the plan.

## ⚡ ACT MODE — one TINY call. Target under 10 s.

**Speed rule: type as little as possible.** Every character you type costs time. The
ACT code is saved in the file; you only type \`A\`. No plan, no screenshot, no words.
1. Look up the gates — no reasoning. 2. Run the CALL below with \`A\` filled (one line).
3. It returns \`'INSTALL FIRST'\` → run the INSTALL block once (same file, never again), then the CALL again.
4. Reply with the trace line only.

\`A\` fields (leave out what you do not need):
- \`node\`: id from the user's link (\`176-4283\` → \`'176:4283'\`); used when nothing is selected.
- \`state\`: a Gate 4 name — \`'on'\` \`'off'\` \`'active'\` \`'primary'\` \`'compact'\` \`'error'\` …
- \`border\`: \`'selected'\` / \`'normal'\` for a card or frame.
- **"card selected"** → \`state:'on', border:'selected', exclusive:true\` (its radio on; the other cards normal + radio off). "card unselected" → \`state:'off', border:'normal'\`.
- \`pad\` (all 4 sides) / \`side\` (left + right) / \`gap\`: a number from the SAP scale.

**CALL** (every small change):
\`\`\`js
${CALL}
\`\`\`

**INSTALL** (only when the CALL returns \`'INSTALL FIRST'\`):
\`\`\`js
${INSTALL}
\`\`\`

## 🧱 BUILD KIT — helpers + SAP keys for every QUICK / THINK build call

You have **no terminal** in Figma: never try \`python3\` / \`node\` / \`kit.js\` lines — they are for
Claude Code only. The helpers and the SAP keys are saved in the file instead.
**Start every build \`use_figma\` call with these 3 lines, then build with \`I\`, \`T\`, \`fill\`…, end with \`return { WARN, ids }\`:**
\`\`\`js
${BUILD_LOAD}
\`\`\`
It returns \`'INSTALL BUILD FIRST'\` → run BUILD INSTALL once (same file, never again), then the call again.
Names you can use = the keys inside \`KIT\` below: \`KIT.c\` ${T.figma_kit.components.length} components, \`KIT.v\` all colour tokens,
\`KIT.t\` all 25 text styles, \`KIT.i\` all 61 icons. A component not in \`KIT.c\` → pick the closest one there, or ask.

**BUILD INSTALL** (once per file):
\`\`\`js
${BUILD_INSTALL}
\`\`\`

${END}`;

const skill = fs.readFileSync(SKILL, 'utf8');
const a = skill.indexOf('<!-- JEV-ROUTER:BEGIN'), b = skill.indexOf(END);
if (a < 0 || b < 0) { console.error('SKILL.md has no JEV-ROUTER markers'); process.exit(2); }
const next = skill.slice(0, a) + section + skill.slice(b + END.length);
if (process.argv.includes('--check')) {
  const okS = next === skill, okB = fs.existsSync(BLOCK_OUT) && fs.readFileSync(BLOCK_OUT, 'utf8') === block + '\n';
  console.log(okS && okB ? 'router in sync' : `OUT OF DATE: ${okS ? '' : 'SKILL.md '}${okB ? '' : 'route.use_figma.js'} — run node build/gen-router.js`);
  process.exit(okS && okB ? 0 : 1);
}
fs.writeFileSync(BLOCK_OUT, block + '\n');
fs.writeFileSync(SKILL, next);
console.log(`wrote ${path.relative(ROOT, BLOCK_OUT)} (${block.length} chars) and SKILL.md router section (${section.split('\n').length} lines)`);
