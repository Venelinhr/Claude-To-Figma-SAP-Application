#!/usr/bin/env node
// make-extension.js — builds the "Make → SAP" Chrome extension. It runs inside the user's own logged-in Chrome (no login is copied anywhere).
//   node build/make-extension.js      writes bridge-out/make-extension/  (Chrome → Extensions → Developer mode → Load unpacked / reload)
// Two jobs:
//  1. Button (works on pages that block bookmarks): reads the app in the current tab — every frame, so it also finds the app inside the
//     figma.com/make preview iframe. Classic SAPUI5 apps → control dump (make-probe.browser.js); any other app (React, UI5 Web Components,
//     plain HTML) → DOM dump (make-probe-dom.browser.js). The dump goes to the clipboard AND to the local bridge (POST /ext/result).
//  2. Link jobs: the SAP Bridge plugin sends a Make share link to the bridge; this extension asks the bridge for work (GET /ext/next),
//     opens the link in a background tab of the user's Chrome, reads it, posts the dump back, closes the tab. So the user only pastes a link.
'use strict';
const fs = require('fs'), path = require('path');
const kit = require('../knowledge/live/kit.json');
const names = [...new Set(Object.keys(kit.vars).map(n => n.split('/').pop()))];
const strip = f => fs.readFileSync(path.join(__dirname, 'templates', f), 'utf8').replace(/^\s*\/\/.*$/gm, '').trim().replace(/;\s*$/, '');
const probe = strip('make-probe.browser.js'), probeDom = strip('make-probe-dom.browser.js');

const manifest = {
  manifest_version: 3, name: process.env.MAKE_EXT_NAME || 'Make → SAP', version: '2.0.0',
  description: 'Read a running Figma Make app for the SAP Bridge Figma plugin. Click once, or paste a Make link in the plugin.',
  permissions: ['activeTab', 'scripting', 'tabs', 'alarms'], host_permissions: ['https://*/*', 'http://localhost/*', 'http://127.0.0.1/*'],
  background: { service_worker: 'background.js' }, action: { default_title: 'Make → SAP: copy this app' },
};

const bg = `// generated by build/make-extension.js — do not edit
const NAMES = ${JSON.stringify(names)};
const BRIDGE = 'http://localhost:${process.env.MAKE_EXT_PORT || 41778}';

// runs inside each frame (MAIN world): returns { kind, dump, n } for the app in this frame, else null
async function PROBE(names) {
  window.__MAKE_CFG = { ret: 1, vars: names };
  if (window.sap && window.sap.ui && window.sap.ui.require) {
    const r = await ${probe};
    return r && r.dump ? { kind: 'sapui5', dump: r.dump, n: (r.dump.match(/"parent":/g) || []).length } : null;
  }
  const h = location.hostname;
  if (/(^|\\.)figma\\.com$/.test(h) || !document.body || document.body.querySelectorAll('*').length < 25) return null;
  const r = await ${probeDom};
  return r && r.dump ? { kind: 'dom', dump: r.dump, n: (r.dump.match(/"i":/g) || []).length } : null;
}
// runs in the top frame: put the text on the clipboard
async function COPY(text) {
  try { await navigator.clipboard.writeText(text); return true; } catch (e) {}
  const ta = document.createElement('textarea'); ta.value = text; ta.style.cssText = 'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0';
  document.body.appendChild(ta); ta.focus(); ta.select(); let ok = false; try { ok = document.execCommand('copy'); } catch (e) {} ta.remove(); return ok;
}
function SAY(msg) { alert(msg); }
const badge = (text, color) => { chrome.action.setBadgeBackgroundColor({ color }); chrome.action.setBadgeText({ text }); setTimeout(() => chrome.action.setBadgeText({ text: '' }), 6000); };

// best result over all frames of a tab (the biggest app wins)
async function readTab(tabId) {
  const res = await chrome.scripting.executeScript({ target: { tabId, allFrames: true }, world: 'MAIN', func: PROBE, args: [NAMES] });
  const hits = res.map(r => r && r.result).filter(Boolean).sort((a, b) => b.n - a.n);
  return hits[0] || null;
}
async function post(pathname, body) {
  try { const r = await fetch(BRIDGE + pathname, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }); return r.ok; } catch (e) { return false; }
}

chrome.action.onClicked.addListener(async tab => {
  const say = msg => chrome.scripting.executeScript({ target: { tabId: tab.id }, func: SAY, args: [msg] }).catch(() => {});
  try {
    const hit = await readTab(tab.id);
    if (!hit) { badge('no', '#c0392b'); return say('Make → SAP: no app found in this tab. Open the Make app (fullscreen or Preview) and click again.'); }
    const sent = await post('/ext/result', { dump: hit.dump, kind: hit.kind });
    const ok = await chrome.scripting.executeScript({ target: { tabId: tab.id, frameIds: [0] }, func: COPY, args: [hit.dump] });
    if (ok[0] && ok[0].result) { badge('ok', '#2e7d32'); return say('Make → SAP: read ' + hit.n + ' ' + (hit.kind === 'dom' ? 'elements' : 'controls') + ' (' + Math.round(hit.dump.length / 1024) + ' KB)' + (sent ? ', sent to the bridge' : '') + '. Now open Figma → SAP Bridge → click inside the plugin window → Cmd+V.'); }
    badge('!', '#c0392b'); say('Make → SAP: could not write to the clipboard. Click the page once, then click the extension again.');
  } catch (e) { badge('err', '#c0392b'); say('Make → SAP failed: ' + (e && e.message || e)); }
});

// ── link jobs from the bridge ──
let busy = false;
async function runJob(job) {
  let tab;
  try {
    tab = await chrome.tabs.create({ url: job.url, active: false });
    const end = Date.now() + 70000; let hit = null;
    while (Date.now() < end && !hit) {
      await new Promise(r => setTimeout(r, 1500));
      try { const t = await chrome.tabs.get(tab.id); if (t.status !== 'complete') continue; hit = await readTab(tab.id); } catch (e) {}
      if (hit && hit.n < 15) hit = null;               // the app is still drawing
    }
    if (!hit) return post('/ext/result', { jobId: job.jobId, error: 'The app did not show up in Chrome within 70 s. Is this Chrome logged in to Figma, and is the link right?' });
    await new Promise(r => setTimeout(r, 1200));       // let layout settle, then read once more
    try { hit = (await readTab(tab.id)) || hit; } catch (e) {}
    await post('/ext/result', { jobId: job.jobId, dump: hit.dump, kind: hit.kind });
  } catch (e) { await post('/ext/result', { jobId: job.jobId, error: String(e && e.message || e) }); }
  finally { if (tab) chrome.tabs.remove(tab.id).catch(() => {}); }
}
async function pollLoop() {
  if (busy) return; busy = true;
  try {
    for (let i = 0; i < 6; i++) {                       // ~ 2.5 min of long polls, then the alarm restarts it
      let job = null;
      try { const r = await fetch(BRIDGE + '/ext/next'); if (r.ok) job = await r.json(); } catch (e) { await new Promise(r => setTimeout(r, 5000)); continue; }
      if (job && job.jobId) await runJob(job);
    }
  } finally { busy = false; }
}
chrome.alarms.create('poll', { periodInMinutes: 0.5 });
chrome.alarms.onAlarm.addListener(a => { if (a.name === 'poll') pollLoop(); });
chrome.runtime.onStartup.addListener(pollLoop); chrome.runtime.onInstalled.addListener(pollLoop);
pollLoop();
`;

const out = process.env.MAKE_EXT_OUT || path.join(__dirname, '..', 'bridge-out', 'make-extension');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2));
fs.writeFileSync(path.join(out, 'background.js'), bg);
console.log(`extension ${(bg.length / 1024).toFixed(0)} KB → ${out}`);
