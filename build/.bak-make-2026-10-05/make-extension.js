#!/usr/bin/env node
// make-extension.js — builds the "Make → SAP" Chrome extension (one click, works on pages that block bookmarks).
//   node build/make-extension.js      writes bridge-out/make-extension/  (Chrome → Extensions → Developer mode → Load unpacked)
// A bookmark is a javascript: URL: pages with a strict Content-Security-Policy (Figma Make preview sites) refuse it, the DevTools console
// does not. An extension injects the same probe through chrome.scripting, which the page policy does not block, into EVERY frame of the
// tab — so it also finds the SAPUI5 app inside the figma.com/make preview iframe. Result: clipboard → SAP Bridge → Cmd+V.
'use strict';
const fs = require('fs'), path = require('path');
const kit = require('../knowledge/live/kit.json');
const names = [...new Set(Object.keys(kit.vars).map(n => n.split('/').pop()))];
const probe = fs.readFileSync(path.join(__dirname, 'templates/make-probe.browser.js'), 'utf8').replace(/^\s*\/\/.*$/gm, '').trim().replace(/;\s*$/, '');

const manifest = {
  manifest_version: 3, name: 'Make → SAP', version: '1.0.0',
  description: 'Copy a running Figma Make (SAPUI5) app for the SAP Bridge Figma plugin. Click once, then Cmd+V in the plugin.',
  permissions: ['activeTab', 'scripting'], host_permissions: ['https://*/*', 'http://localhost/*', 'http://127.0.0.1/*'],
  background: { service_worker: 'background.js' }, action: { default_title: 'Make → SAP: copy this app' },
};

const bg = `// generated by build/make-extension.js — do not edit
const NAMES = ${JSON.stringify(names)};

// runs inside each frame (MAIN world): returns the dump text if this frame is a SAPUI5 app, else null
async function PROBE(names) {
  if (!window.sap || !window.sap.ui || !window.sap.ui.require) return null;
  window.__MAKE_CFG = { ret: 1, vars: names };
  const r = await ${probe};
  return r && r.dump ? r.dump : null;
}
// runs in the top frame: put the text on the clipboard
async function COPY(text) {
  try { await navigator.clipboard.writeText(text); return true; } catch (e) {}
  const ta = document.createElement('textarea'); ta.value = text; ta.style.cssText = 'position:fixed;left:0;top:0;width:1px;height:1px;opacity:0';
  document.body.appendChild(ta); ta.focus(); ta.select(); let ok = false; try { ok = document.execCommand('copy'); } catch (e) {} ta.remove(); return ok;
}
function SAY(msg) { alert(msg); }

const badge = (text, color) => { chrome.action.setBadgeBackgroundColor({ color }); chrome.action.setBadgeText({ text }); setTimeout(() => chrome.action.setBadgeText({ text: '' }), 6000); };

chrome.action.onClicked.addListener(async tab => {
  const say = msg => chrome.scripting.executeScript({ target: { tabId: tab.id }, func: SAY, args: [msg] }).catch(() => {});
  try {
    const res = await chrome.scripting.executeScript({ target: { tabId: tab.id, allFrames: true }, world: 'MAIN', func: PROBE, args: [NAMES] });
    const hit = res.find(r => r && r.result);
    if (!hit) { badge('no', '#c0392b'); return say('Make → SAP: no SAPUI5 app found in this tab. Open the Make app with its Play (Preview) button and click again.'); }
    const dump = hit.result, n = (dump.match(/"parent":/g) || []).length;
    const ok = await chrome.scripting.executeScript({ target: { tabId: tab.id, frameIds: [0] }, func: COPY, args: [dump] });
    if (ok[0] && ok[0].result) { badge('ok', '#2e7d32'); return say('Make → SAP: copied ' + n + ' controls (' + Math.round(dump.length / 1024) + ' KB). Now open Figma → SAP Bridge → click inside the plugin window → Cmd+V.'); }
    badge('!', '#c0392b'); say('Make → SAP: could not write to the clipboard. Click the page once, then click the extension again.');
  } catch (e) { badge('err', '#c0392b'); say('Make → SAP failed: ' + (e && e.message || e)); }
});
`;

const out = path.join(__dirname, '..', 'bridge-out', 'make-extension');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2));
fs.writeFileSync(path.join(out, 'background.js'), bg);
console.log(`extension ${(bg.length / 1024).toFixed(0)} KB → ${out}`);
